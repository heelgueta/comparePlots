def unq(t):
    return t.encode().decode("unicode_escape").encode("latin-1").decode("utf-8") if "\\" in t else t

def esc(t):
    return t.replace("\\", "\\\\").replace('"', '\\"')

text = open(PO, encoding="utf-8").read()
blocks = text.split("\n\n")
out, missing = [], []
for b in blocks:
    m = re.search(r'^msgid (.*?)^msgstr ', b, re.M | re.S)
    if not m:
        out.append(b); continue
    mid = "".join(re.findall(r'"(.*)"', m.group(1)))
    if mid == "":
        out.append(b); continue                       # the header block
    if mid not in ES:
        missing.append(mid); out.append(b); continue
    head = b[:m.end() - len("msgstr ")]
    out.append(head + 'msgstr "%s"' % esc(ES[mid]))
open(PO, "w", encoding="utf-8").write("\n\n".join(out))
extra = sorted(set(ES) - {"".join(re.findall(r'"(.*)"', x.group(1))) for x in re.finditer(r'^msgid (.*?)^msgstr ', text, re.M | re.S)})
print("translated:", len(ES) - len(extra), " missing:", len(missing), " dictionary entries not in the .po:", len(extra))
for x in missing: print("  MISSING:", x[:90])
for x in extra[:10]: print("  UNUSED:", x[:90])
